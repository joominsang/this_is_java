package com.mjc813;

public class Student5 {
    private String name;
    private String sex;
    private int score;

    public Student5(String name, String sex, int score) {
        this.name = name;
        this.sex = sex;
        this.score = score;
    }
    public String getName() {
        return name;
    }
    public String getSex() {
        return sex;
    }
    public int getScore() {
        return score;
    }
}
